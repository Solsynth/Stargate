/** Display name for a provider slug; unknown slugs are prettified, not hidden. */
export function providerLabel(provider: string): string {
  const known = PROVIDER_MARKS[provider.toLowerCase()]
  if (known) return known.label
  return provider.charAt(0).toUpperCase() + provider.slice(1)
}

/**
 * The display data for a provider slug: its brand name and silhouette path
 * data. `ProviderMark.vue` reads it; an unknown slug gets the monogram.
 */
export function providerInfo(provider: string): ProviderMark | undefined {
  return PROVIDER_MARKS[provider.toLowerCase()]
}
